func RecordConsumeLog(c *gin.Context, userId int, params RecordConsumeLogParams) {
	if !common.LogConsumeEnabled {
		return
	}
	logger.LogInfo(c, fmt.Sprintf("record consume log: userId=%d, params=%s", userId, common.GetJsonString(params)))
	username := c.GetString("username")
	requestId := c.GetString(common.RequestIdKey)
	upstreamRequestId := c.GetString(common.UpstreamRequestIdKey)
	createdAt := common.GetTimestamp()
	// 记录调用方 User-Agent 进 other(key 管理页"最近使用的 UA"展示用),
	// 截断防超长 header 撑爆 other 列。
	if params.Other == nil {
		params.Other = make(map[string]interface{})
	}
	if c != nil && c.Request != nil {
		if ua := c.Request.UserAgent(); ua != "" {
			const maxUserAgentLen = 255
			if len(ua) > maxUserAgentLen {
				ua = ua[:maxUserAgentLen]
			}
			params.Other["user_agent"] = ua
		}
		// 管理员审计 IP: 无条件记录进 other.admin_info(非管理员日志视图会
		// 剥离整个 admin_info),不受用户「记录 IP」开关限制;开关只管 ip 列。
		if ip := c.ClientIP(); ip != "" {
			adminInfo, ok := params.Other["admin_info"].(map[string]interface{})
			if !ok {
				adminInfo = make(map[string]interface{})
				params.Other["admin_info"] = adminInfo
			}
			adminInfo["admin_ip"] = ip
		}
	}
	otherStr := common.MapToJsonStr(params.Other)
	// 判断是否需要记录 IP
	needRecordIp := false
	if settingMap, err := GetUserSetting(userId, false); err == nil {
		if settingMap.RecordIpLog {
			needRecordIp = true
		}
	}
	log := &Log{
		UserId:           userId,
		Username:         username,
		CreatedAt:        createdAt,
		Type:             LogTypeConsume,
		Content:          params.Content,
		PromptTokens:     params.PromptTokens,
		CompletionTokens: params.CompletionTokens,
		TokenName:        params.TokenName,
		ModelName:        params.ModelName,
		Quota:            params.Quota,
		ChannelId:        params.ChannelId,
		TokenId:          params.TokenId,
		UseTime:          params.UseTimeSeconds,
		IsStream:         params.IsStream,
		Group:            params.Group,
		Ip: func() string {
			if needRecordIp {
				return c.ClientIP()
			}
			return ""
		}(),
		RequestId:         requestId,
		UpstreamRequestId: upstreamRequestId,
		Other:             otherStr,
	}
	err := createLog(log)
	if err != nil {
		logger.LogError(c, "failed to record log: "+err.Error())
	}
	if common.DataExportEnabled {
		LogQuotaData(QuotaDataLogParams{
			UserID:    userId,
			Username:  username,
			ModelName: params.ModelName,
			Quota:     params.Quota,
			CreatedAt: createdAt,
			TokenUsed: params.PromptTokens + params.CompletionTokens,
			UseGroup:  params.Group,
			TokenID:   params.TokenId,
			ChannelID: params.ChannelId,
			NodeName:  common.NodeName,
		})
	}
}

